_CHAT_TSX = '''import { useEffect, useState } from "react";
import { health } from "../api";
import { RealtimeClient } from "../realtime";

export function ChatPage() {
  const [status, setStatus] = useState("Checking API…");
  const [messages, setMessages] = useState<string[]>([]);
  const [value, setValue] = useState("");
  const [client, setClient] = useState<RealtimeClient | null>(null);
  useEffect(() => { health().then(() => setStatus("API healthy")).catch((error) => setStatus(error.message)); }, []);
  function connect() { const next = new RealtimeClient("/ws/chat", (message) => setMessages((old) => [...old, JSON.stringify(message)])); setClient(next); }
  function send() { if (value && client) { client.send({ message: value }); setValue(""); } }
  return <section><h1>Realtime chat</h1><p>{status}</p><button onClick={connect} disabled={!!client}>Connect</button><div className="messages">{messages.map((message, index) => <p key={index}>{message}</p>)}</div><div className="composer"><input value={value} onChange={(event) => setValue(event.target.value)} placeholder="Message" /><button onClick={send}>Send</button></div></section>;
}
'''

_ROOM_TSX = '''import { useRef, useState } from "react";
import { RealtimeClient } from "../realtime";
import { createPeerConnection } from "../webrtc";

export function RoomPage() {
  const [room, setRoom] = useState("demo");
  const [status, setStatus] = useState("Choose a room, then join from another browser.");
  const localVideo = useRef<HTMLVideoElement>(null);
  async function join() {
    let connection: ReturnType<typeof createPeerConnection> | undefined;
    const client = new RealtimeClient(`/signaling/${encodeURIComponent(room)}`, async (message: any) => {
      setStatus(`Signal: ${message.event}`);
      if (message.event === "peer-joined") await connection?.offer();
      if (["offer", "answer", "ice-candidate"].includes(message.event)) await connection?.accept(message);
    });
    connection = createPeerConnection(client);
    const stream = await navigator.mediaDevices.getUserMedia({ video: true, audio: true });
    stream.getTracks().forEach((track) => connection.peer.addTrack(track, stream));
    if (localVideo.current) localVideo.current.srcObject = stream;
    setStatus("Joined signaling room. Browser permission and STUN/TURN policy affect calls.");
  }
  return <section><h1>WebRTC room</h1><p>{status}</p><div className="composer"><input value={room} onChange={(event) => setRoom(event.target.value)} /><button onClick={join}>Join room</button></div><video ref={localVideo} autoPlay muted playsInline /></section>;
}
'''

