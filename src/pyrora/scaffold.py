_REALTIME_TS = '''export class RealtimeClient {
  private socket: WebSocket;
  constructor(path: string, onMessage: (message: unknown) => void) {
    const explicit = import.meta.env.VITE_WS_URL as string | undefined;
    const origin = explicit ?? `${location.protocol === "https:" ? "wss" : "ws"}://${location.host}`;
    this.socket = new WebSocket(`${origin}${path}`);
    this.socket.onmessage = (event) => onMessage(JSON.parse(event.data));
  }
  send(message: unknown) { this.socket.send(JSON.stringify(message)); }
  close() { this.socket.close(); }
}
'''

_WEBRTC_TS = '''import type { RealtimeClient } from "./realtime";

export function createPeerConnection(signaling: RealtimeClient, peerId?: string) {
  const peer = new RTCPeerConnection({ iceServers: [{ urls: "stun:stun.l.google.com:19302" }] });
  peer.onicecandidate = ({ candidate }) => { if (candidate) signaling.send({ event: "ice-candidate", to: peerId, candidate }); };
  return {
    peer,
    async offer() { const offer = await peer.createOffer(); await peer.setLocalDescription(offer); signaling.send({ event: "offer", to: peerId, sdp: offer }); },
    async accept(message: any) {
      if (message.event === "offer") { await peer.setRemoteDescription(message.sdp); const answer = await peer.createAnswer(); await peer.setLocalDescription(answer); signaling.send({ event: "answer", to: message.from, sdp: answer }); }
      if (message.event === "answer") await peer.setRemoteDescription(message.sdp);
      if (message.event === "ice-candidate" && message.candidate) await peer.addIceCandidate(message.candidate);
    },
    hangup() { signaling.send({ event: "hangup", to: peerId }); peer.close(); }
  };
}
'''

