"""Project and optional React/Vite starter generation."""

from __future__ import annotations

import re
from pathlib import Path


def create_project(destination: Path, *, react: bool = False) -> None:
    """Create a non-destructive runnable Pyrora project."""
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", destination.name):
        raise ValueError("Project name must start with a letter and use letters, numbers, '_' or '-'.")
    if destination.exists():
        raise RuntimeError(f"Destination already exists: {destination}")
    destination.mkdir(parents=True)
    _write(destination / "pyproject.toml", _project_pyproject(destination.name))
    _write(destination / "README.md", _project_readme(destination.name, react))
    _write(destination / "app.py", "from backend.app import app\n")
    _write(destination / "backend" / "__init__.py", "")
    _write(destination / "backend" / "app.py", _backend_app(react))
    _write(destination / "backend" / "templates" / "home.html", _HOME_TEMPLATE)
    _write(destination / "backend" / "static" / ".gitkeep", "")
    if react:
        _create_react(destination / "frontend")


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _project_pyproject(name: str) -> str:
    normalized = name.lower().replace("_", "-")
    return f'''[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "{normalized}"
version = "0.1.0"
requires-python = ">=3.10"
dependencies = ["pyrora>=0.1.0"]

[tool.setuptools.packages.find]
include = ["backend*"]
'''


